"""Prepare native AGNOS programs and the bundled QCOM models before services start."""
import argparse
import gzip
import hashlib
import json
import os
import platform
import re
import shutil
import stat
import subprocess
import sys
import sysconfig
import tempfile
from pathlib import Path

BUNDLE = 'prebuilt_assets'
RECEIPT = '.carrot_boot_build.json'
REPAIR = '.carrot_boot_repair'
MODELS = 'openpilot/selfdrive/modeld/models/'
REQUIRED = {
  'openpilot/common/params_pyx.so', 'openpilot/selfdrive/pandad/pandad', 'openpilot/system/camerad/camerad',
  'openpilot/system/loggerd/loggerd', 'openpilot/system/loggerd/encoderd',
  MODELS + 'tg_input_devices.json', MODELS + 'dm_warp_1344x760_tinygrad.pkl', MODELS + 'dm_warp_1928x1208_tinygrad.pkl',
  MODELS + 'dmonitoring_model_metadata.pkl', MODELS + 'driving_tinygrad.pkl.chunkmanifest', MODELS + 'dmonitoring_model_tinygrad.pkl.chunkmanifest',
}
OUTPUT_ROOTS = {'openpilot', 'opendbc_repo', 'msgq_repo', 'panda', 'rednose_repo'}
MODEL_STAMPS = {MODELS + '.build_stamp', MODELS + '.big_model_build_stamp'}


def git(root, *args):
  return subprocess.check_output(['git', *args], cwd=root, stderr=subprocess.DEVNULL)


def source_tree(root):
  tree = [row for row in git(root, 'ls-tree', '-z', 'HEAD').split(b'\0') if row and row.split(b'\t', 1)[1] != BUNDLE.encode()]
  return hashlib.sha256(b'\0'.join(tree)).hexdigest()


def identity(root):
  device = Path('/sys/firmware/devicetree/base/model').read_text().strip('\x00\n')
  if device not in ('comma tizi', 'comma mici') or not Path('/AGNOS').is_file() or platform.machine() != 'aarch64':
    raise ValueError('requires a C3X or C4 AGNOS build')
  if any(os.environ.get(key) for key in ('SCONSFLAGS', 'BIG_INTO_SMALL', 'BUILD_USB_GPU_MODEL', 'SUNNY_COMPILE_INTERNAL')):
    raise ValueError('custom build configuration')
  # The packaging-only commit changes this directory. All other Git trees
  # (including the launcher, compiler, Panda, ONNX and both camera warps) bind the build.
  native_wheels = sorted(p.name for p in Path(sysconfig.get_path('purelib')).glob('*.dist-info')
                         if p.name.lower().startswith(('comma_deps_', 'numpy-', 'casadi-', 'cython-', 'scons-')))
  return {'format': 1, 'source': source_tree(root), 'native_wheels': native_wheels,
          'os': Path('/VERSION').read_text().strip(), 'kernel': platform.release(), 'abi': sys.implementation.cache_tag,
          'soc': Path('/sys/devices/soc0/soc_id').read_text().strip(), 'gpu': Path('/sys/class/kgsl/kgsl-3d0/gpu_model').read_text().strip()}


def git_paths(root, *args):
  return {os.fsdecode(p) for p in git(root, 'ls-files', '-z', *args).split(b'\0') if p}


def generated_data(name):
  p = Path(name)
  return ((p.parent.as_posix() == 'opendbc_repo/opendbc/dbc' and name.endswith('_generated.dbc')) or
          (p.parent.as_posix() == 'openpilot/selfdrive/assets/fonts' and p.suffix in ('.fnt', '.png')))


def check_checkout(root, files, data, publishing=False):
  excludes = [':(exclude)' + p for p in sorted(data)]
  if publishing:
    excludes.append(':(exclude)' + BUNDLE)
  git(root, 'diff', '--quiet', 'HEAD', '--', '.', *excludes)
  # The offline-wheel bootstrap owns pydeps. All other nonignored build inputs
  # must be tracked, including newly added scripts, headers and tinygrad files.
  extra = git_paths(root, '--others', '--exclude-standard', '--', '.', ':(exclude)pydeps', ':(exclude)' + BUNDLE)
  unknown = extra.difference(files, MODEL_STAMPS)
  # The DBC generator also leaves its intermediate text beside the Python
  # source. Accept it only when its contents match the verified final DBC.
  for name in tuple(unknown):
    path = Path(name)
    final = 'opendbc_repo/opendbc/dbc/' + path.stem + '_generated.dbc'
    if name.startswith('opendbc_repo/opendbc/dbc/generator/') and path.suffix == '.dbc' and final in files:
      header = ('CM_ "AUTOGENERATED FILE, DO NOT EDIT";\n\nCM_ "' + path.name + ' starts here";\n').encode()
      if (root / final).is_file() and (root / final).read_bytes() == header + (root / name).read_bytes():
        unknown.remove(name)
  if unknown:
    raise ValueError('untracked input ' + min(unknown))


def output_path(root, name):
  path = Path(name)
  if not path.parts or path.parts[0] not in OUTPUT_ROOTS or '..' in path.parts or str(path) != name:
    raise ValueError('invalid build output path')
  dest = root / path
  if dest.is_symlink() or dest.parent.resolve() != dest.parent:
    raise ValueError(f'build output uses symlink: {name}')
  return dest


def fingerprint(path):
  s = path.stat()
  if not stat.S_ISREG(s.st_mode):
    raise ValueError(f'not a regular file: {path.name}')
  return [s.st_size, stat.S_IMODE(s.st_mode), s.st_dev, s.st_ino, s.st_mtime_ns, s.st_ctime_ns]


def digest(path):
  with path.open('rb') as f:
    return hashlib.file_digest(f, 'sha256').hexdigest()


def atomic_json(path, value):
  with tempfile.NamedTemporaryFile('w', dir=path.parent, prefix='.carrot-boot-', suffix='.tmp', delete=False) as f:
    tmp = Path(f.name)
    try:
      json.dump(value, f, separators=(',', ':'), sort_keys=True)
      f.flush()
      os.fsync(f.fileno())
      f.close()
      tmp.replace(path)
    finally:
      tmp.unlink(missing_ok=True)


def read_json(path):
  return json.loads(path.read_text())


def check_models(root, files):
  if not REQUIRED.issubset(files):
    raise ValueError('incomplete native or camera model target list')
  devices = read_json(root / MODELS / 'tg_input_devices.json')
  if devices['openpilot.selfdrive.modeld.modeld']['default']['WARP_DEV'] != 'QCOM':
    raise ValueError('bundled camera model was not built for QCOM')
  for base in ('driving_tinygrad.pkl', 'dmonitoring_model_tinygrad.pkl'):
    prefix = MODELS + base
    count = int((root / (prefix + '.chunkmanifest')).read_text())
    if not 1 <= count <= 64:
      raise ValueError(f'invalid model chunk count: {base}')
    for i in range(1, count + 1):
      name = f'{prefix}.chunk{i:02d}of{count:02d}'
      if name not in files or (i == 1 and not (root / name).stat().st_size):
        raise ValueError(f'incomplete model: {base}')


def record(root, targets, publish=False):
  key = identity(root)
  outputs = set(targets.read_text().splitlines())
  tracked = git_paths(root)
  # A clean SCons build also regenerates a few versioned data assets. Keep
  # their exact local signatures, but always distribute their Git originals.
  data = {name for name in outputs & tracked if generated_data(name)}
  files = sorted((outputs - tracked) | data)
  check_checkout(root, files, data, publishing=publish)
  check_models(root, files)
  artifacts, stats = {}, {}
  folder = root / BUNDLE
  if publish:
    folder.mkdir(exist_ok=True)
  for name in files:
    path = output_path(root, name)
    sig = fingerprint(path)
    sha = digest(path)
    artifacts[name] = [sha, *sig[:2]]
    stats[name] = sig
    if publish and name not in data:
      blob = folder / (sha + '.gz')
      good = False
      if blob.is_file():
        try:
          with gzip.open(blob, 'rb') as zipped:
            good = hashlib.file_digest(zipped, 'sha256').hexdigest() == sha
        except (OSError, EOFError):
          pass
      if not good:
        with tempfile.NamedTemporaryFile(dir=folder, prefix='.carrot-boot-', suffix='.tmp', delete=False) as out:
          tmp = Path(out.name)
          try:
            with gzip.GzipFile(filename='', fileobj=out, mode='wb', compresslevel=3, mtime=0) as z, path.open('rb') as src:
              shutil.copyfileobj(src, z)
            out.close()
            tmp.replace(blob)
          finally:
            tmp.unlink(missing_ok=True)
    if fingerprint(path) != sig:
      raise ValueError(f'output changed during preparation: {name}')
  catalog = {'identity': key, 'files': artifacts}
  if publish:
    shipped = {name: row for name, row in artifacts.items() if name not in data}
    atomic_json(folder / 'manifest.json', {'identity': key, 'files': shipped})
    keep = {row[0] for row in shipped.values()}
    for blob in folder.glob('*.gz'):
      if re.fullmatch('[0-9a-f]{64}', blob.stem) and blob.stem not in keep:
        blob.unlink()
  atomic_json(root / RECEIPT, {**catalog, 'revision': git(root, 'rev-parse', 'HEAD').decode().strip(), 'stats': stats})
  (root / REPAIR).unlink(missing_ok=True)
  print(f'Boot prebuild: {"packaged" if publish else "recorded"} {len(files)} verified outputs', flush=True)


def install_blob(blob, dest, sha, size, mode):
  if not re.fullmatch('[0-9a-f]{64}', sha) or mode not in (0o644, 0o755, 0o664, 0o775, 0o444, 0o555) or size < 0:
    raise ValueError('invalid release output metadata')
  dest.parent.mkdir(parents=True, exist_ok=True)
  with tempfile.NamedTemporaryFile(dir=dest.parent, prefix='.carrot-boot-', suffix='.tmp', delete=False) as f:
    tmp = Path(f.name)
    try:
      remaining = size
      with gzip.open(blob, 'rb') as src:
        while chunk := src.read(min(remaining + 1, 1024 * 1024)):
          remaining -= len(chunk)
          if remaining < 0:
            raise ValueError(f'oversize release output: {dest.name}')
          f.write(chunk)
      f.close()
      if remaining or digest(tmp) != sha:
        raise ValueError(f'release checksum mismatch: {dest.name}')
      tmp.chmod(mode)
      tmp.replace(dest)
    finally:
      tmp.unlink(missing_ok=True)


def prepare(root):
  key = identity(root)
  revision = git(root, 'rev-parse', 'HEAD').decode().strip()
  try:
    local = read_json(root / RECEIPT)
  except (OSError, ValueError):
    local = {}
  cached = (isinstance(local, dict) and local.get('revision') == revision and local.get('identity') == key and
            isinstance(local.get('stats'), dict) and isinstance(local.get('files'), dict) and REQUIRED.issubset(local['files']))
  if cached:
    catalog = local
  else:
    git(root, 'ls-files', '--error-unmatch', '--', BUNDLE + '/manifest.json')
    catalog = read_json(root / BUNDLE / 'manifest.json')
    if catalog['identity'] != key:
      raise ValueError('release does not match this source or AGNOS runtime')
  files = catalog['files']
  data = git_paths(root).intersection(files)
  if not REQUIRED.issubset(files) or data and (not cached or not all(map(generated_data, data))):
    raise ValueError('incomplete manifest or collision with source')
  check_checkout(root, files, data)
  stats, damaged = {}, []
  installing = False
  for name, (sha, size, mode) in files.items():
    path = output_path(root, name)
    try:
      sig = fingerprint(path)
    except FileNotFoundError:
      sig = None
    unchanged = cached and sig is not None and sig == local['stats'].get(name)
    if not unchanged and (sig is None or sig[:2] != [size, mode] or digest(path) != sha):
      if cached:
        damaged.append(name)
        continue
      if not installing:
        # An interrupted direct installation may have a mix of old and new
        # outputs. A source fallback must rebuild them even with unchanged inputs.
        (root / REPAIR).write_text(''.join(p + '\n' for p in files))
        installing = True
      install_blob(root / BUNDLE / (sha + '.gz'), path, sha, size, mode)
      sig = fingerprint(path)
    stats[name] = sig
  if damaged:
    (root / REPAIR).write_text(''.join(name + '\n' for name in damaged))
    raise ValueError('rebuilding changed or missing ' + damaged[0])
  check_models(root, files)
  if not cached or stats != local['stats']:
    atomic_json(root / RECEIPT, {'identity': key, 'revision': revision, 'files': files, 'stats': stats})
  (root / REPAIR).unlink(missing_ok=True)
  print(f'Boot prebuild: {"reused" if cached else "installed"} {len(files)} verified outputs', flush=True)


def main():
  parser = argparse.ArgumentParser(description=__doc__)
  parser.add_argument('operation', choices=['prepare', 'record', 'publish'])
  parser.add_argument('targets', type=Path, nargs='?')
  args = parser.parse_args()
  root = Path(__file__).resolve().parents[3]
  try:
    if args.operation == 'prepare':
      prepare(root)
    else:
      if args.targets is None:
        parser.error('target inventory required')
      record(root, args.targets, publish=args.operation == 'publish')
  except (OSError, ValueError, TypeError, KeyError, EOFError, subprocess.CalledProcessError) as exc:
    print(f'Boot prebuild unavailable: {exc}', flush=True)
    return 1
  return 0


if __name__ == '__main__':
  sys.exit(main())
