export const assetManifestDefinition = Object.freeze({
  schemaVersion: 1,
  output: "generated/asset-manifest.json",
});

function sha256(bytes) {
  return createHash("sha256").update(bytes).digest("hex");
}

function assetContentHash(bytes) {
  const normalized = Buffer.from(bytes.toString("utf8").replaceAll("\r\n", "\n"), "utf8");
  return sha256(normalized);
}

function workerOutput(definition) {
  return definition.output || definition.path;
}

async function normalizeGeneratedText(path) {
  const source = await readFile(path, "utf8");
  const normalized = source
    .replace(/[ \t]+$/gm, "")
    .replace(/^ +(?=\t)/gm, "");
  if (normalized !== source) await writeFile(path, normalized, "utf8");
}

export async function readValidatedDriveContentCatalog(root = webRoot) {
  const sourcePath = resolve(root, driveContentCatalogDefinition.source);
  let catalog;
  try {
    catalog = JSON.parse(await readFile(sourcePath, "utf8"));
  } catch (error) {
    throw new Error(`Drive content catalog cannot be read: ${sourcePath}`, { cause: error });
  }
  const normalized = validateDriveContentCatalog(catalog);
  const catalogIds = normalized.contents.map(({ id }) => id);
  const factoryIds = [...driveContentCatalogDefinition.factoryIds];
  if (catalogIds.length !== factoryIds.length
      || catalogIds.some((id, index) => id !== factoryIds[index])) {
    throw new Error(
      `Drive content catalog/factory ids must match exactly: catalog=[${catalogIds.join(",")}] factories=[${factoryIds.join(",")}]`,
    );
  }
  return normalized;
}

async function buildAssetManifest(outputRoot) {
  const assets = [];
  for (const definition of bundleDefinitions) {
    const bytes = await readFile(resolve(outputRoot, definition.output));
    assets.push({
      id: definition.id,
      kind: definition.kind,
      source: definition.entry,
      path: definition.output,
      hash: assetContentHash(bytes),
    });
  }
  for (const definition of workerDefinitions) {
    const path = workerOutput(definition);
    const sourceRoot = definition.entry ? outputRoot : webRoot;
    const bytes = await readFile(resolve(sourceRoot, path));
    assets.push({
      id: definition.id,
      kind: "worker",
      path,
      hash: assetContentHash(bytes),
    });
  }

  const ids = new Set(assets.map(({ id }) => id));
  const paths = new Set(assets.map(({ path }) => path));
  if (ids.size !== assets.length || paths.size !== assets.length) {
    throw new Error("Asset manifest ids and paths must be unique");
  }
  return { schemaVersion: assetManifestDefinition.schemaVersion, assets };
}

async function writeAssetManifest(outputRoot) {
  const manifest = await buildAssetManifest(outputRoot);
  const outputPath = resolve(outputRoot, assetManifestDefinition.output);
  const temporaryPath = `${outputPath}.${process.pid}-${randomUUID()}.tmp`;
  await mkdir(dirname(outputPath), { recursive: true });
  try {
    await writeFile(temporaryPath, `${JSON.stringify(manifest, null, 2)}\n`, "utf8");
    await rename(temporaryPath, outputPath);
  } finally {
    await rm(temporaryPath, { force: true });
  }
}

