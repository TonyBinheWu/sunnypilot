export async function buildWeb({ outputRoot } = {}) {
  const requestedOutputRoot = outputRoot ?? process.env.CARROT_WEB_TEST_OUTDIR;
  const buildOutputRoot = requestedOutputRoot ? resolve(requestedOutputRoot) : webRoot;

  await readValidatedDriveContentCatalog();

  for (const definition of bundleDefinitions) {
    const bannerType = definition.output.endsWith(".css") ? "css" : "js";
    await build({
      entryPoints: [resolve(webRoot, definition.entry)],
      outfile: resolve(buildOutputRoot, definition.output),
      bundle: true,
      platform: "browser",
      format: "iife",
      target: ["chrome100"],
      charset: "utf8",
      legalComments: "none",
      minify: true,
      sourcemap: false,
      banner: { [bannerType]: definition.banner },
    });
    await normalizeGeneratedText(resolve(buildOutputRoot, definition.output));
  }
  for (const definition of workerDefinitions) {
    if (!definition.entry) continue;
    await build({
      entryPoints: [resolve(webRoot, definition.entry)],
      outfile: resolve(buildOutputRoot, workerOutput(definition)),
      bundle: true,
      platform: "browser",
      format: "iife",
      target: ["chrome100"],
      charset: "utf8",
      legalComments: "none",
      minify: true,
      sourcemap: false,
      banner: { js: definition.banner },
    });
    await normalizeGeneratedText(resolve(buildOutputRoot, workerOutput(definition)));
  }
  await buildTraditionalGuide(buildOutputRoot);
  await writeAssetManifest(buildOutputRoot);
}

if (process.argv[1] && resolve(process.argv[1]) === resolve(buildFile)) await buildWeb();
